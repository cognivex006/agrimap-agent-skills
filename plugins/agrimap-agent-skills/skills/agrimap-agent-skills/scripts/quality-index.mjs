// Renders references/quality-security-index.md (6.3.0) from
// assets/quality-security-index.json and assets/sec-coverage.json. Pure function;
// tools/sync-adapters.mjs writes the file, a test rejects hand edits.
export function renderQualitySecurityIndex(index, coverage) {
  const kinds = { policy: "Policy", matrix: "Matrix", metadata: "Metadata", examples: "Examples", tool: "Tool" };
  const link = (p) => `[${p.split("/").pop()}](${p})`;
  const counts = {};
  for (const c of coverage.classes) counts[c.scanner.status] = (counts[c.scanner.status] || 0) + 1;
  const surface = (s) => ({ csharp: "C#", typescript: "TS", angular: "Angular", javascript: "JS", html: "HTML", sql: "SQL", nginx: "nginx", docker: "Docker/CI" }[s] || s);
  return [
    "# Quality and security index",
    "",
    "<!-- Generated by npm run sync from assets/quality-security-index.json and assets/sec-coverage.json. Do not edit by hand. -->",
    "",
    "Which file owns each quality or security concern. Read the owner; other files link to it instead of repeating it.",
    "",
    "## Owners",
    "",
    "| Concern | Kind | Owner |",
    "| --- | --- | --- |",
    ...index.concerns.map((c) => `| ${c.concern} | ${kinds[c.kind] || c.kind} | ${link(c.owner)} |`),
    "",
    "## Security coverage",
    "",
    `Golden Lint ${coverage.goldenLint.version} scanner status: ${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(", ")}. A class without a detector is still a Golden rule: authoring follows it and review checks it by hand.`,
    "",
    "| Class | Title | Surfaces | Scanner | Detectors |",
    "| --- | --- | --- | --- | --- |",
    ...coverage.classes.map((c) => `| ${c.id} | ${c.title} | ${c.authoring.surfaces.map(surface).join(", ") || "—"} | ${c.scanner.status} | ${c.scanner.detectors.length} |`),
    "",
  ].join("\n");
}
